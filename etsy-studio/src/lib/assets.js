// Private asset library. Files live outside the web root under random names; the original
// filename is metadata only, so nothing a user types can become a path.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { ETSY_LIMITS, getConfig } from './config.js'
import { audit, json, newId, now, parse } from './db.js'
import { imageSize } from './png.js'

/** Detect type from content, not the extension. */
export function sniff(buf) {
  const h = buf.subarray(0, 16)
  const ascii = (a, b) => buf.toString('latin1', a, b)
  if (h[0] === 0x89 && ascii(1, 4) === 'PNG') return 'image/png'
  if (h[0] === 0xff && h[1] === 0xd8 && h[2] === 0xff) return 'image/jpeg'
  if (ascii(0, 4) === 'GIF8') return 'image/gif'
  if (ascii(0, 4) === 'RIFF' && ascii(8, 12) === 'WEBP') return 'image/webp'
  if (ascii(4, 8) === 'ftyp') return /^qt/.test(ascii(8, 10)) ? 'video/quicktime' : 'video/mp4'
  if (ascii(0, 4) === '%PDF') return 'application/pdf'
  if (h[0] === 0x50 && h[1] === 0x4b && h[2] === 0x03 && h[3] === 0x04) return 'application/zip'
  if (/^\s*<(\?xml|svg)/i.test(ascii(0, 64)) && /<svg/i.test(ascii(0, 512))) return 'image/svg+xml'
  return 'application/octet-stream'
}

export const ROLE_RULES = {
  image: { mimes: ['image/png', 'image/jpeg', 'image/gif', 'image/webp'], max: ETSY_LIMITS.imageMaxBytes },
  video: { mimes: ['video/mp4', 'video/quicktime'], max: ETSY_LIMITS.videoMaxBytes },
  file: {
    mimes: ['application/pdf', 'application/zip', 'image/png', 'image/jpeg', 'image/svg+xml', 'image/gif', 'image/webp', 'application/octet-stream'],
    max: ETSY_LIMITS.fileMaxBytes,
  },
}

export function safeFilename(name) {
  const base = path.basename(String(name || 'file')).replace(/[^\w.\- ]+/g, '_').replace(/^\.+/, '').slice(0, 100)
  return base || 'file'
}

export function kindOf(mime) {
  if (mime.startsWith('image/') && mime !== 'image/svg+xml') return 'image'
  if (mime.startsWith('video/')) return 'video'
  return 'file'
}

export function saveAsset(db, shop, buffer, { filename, source = 'upload', meta = {} } = {}) {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) throw new Error('Empty file')
  const max = Math.max(...Object.values(ROLE_RULES).map((r) => r.max))
  if (buffer.length > max) throw new Error(`File is larger than ${Math.round(max / 1048576)} MB`)
  const mime = sniff(buffer)
  const id = newId('ast')
  const ext = { 'image/png': '.png', 'image/jpeg': '.jpg', 'image/gif': '.gif', 'image/webp': '.webp', 'video/mp4': '.mp4', 'video/quicktime': '.mov', 'application/pdf': '.pdf', 'application/zip': '.zip', 'image/svg+xml': '.svg' }[mime] ?? '.bin'
  const stored = `${id}${ext}`
  const dir = getConfig().paths.assets
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, stored), buffer)
  const dims = mime.startsWith('image/') ? imageSize(buffer, mime) : null
  db.prepare(
    `INSERT INTO assets (id, shop_id, kind, mime, size, filename, stored_name, sha256, width, height, source, meta_json, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
  ).run(id, shop.shop_id, kindOf(mime), mime, buffer.length, safeFilename(filename), stored, crypto.createHash('sha256').update(buffer).digest('hex'), dims?.width ?? null, dims?.height ?? null, source, json(meta), now())
  audit(db, 'asset.add', { shopId: shop.shop_id, target: id, detail: { mime, size: buffer.length, source } })
  return getAsset(db, id)
}

export function getAsset(db, id) {
  const r = db.prepare('SELECT * FROM assets WHERE id = ?').get(id)
  return r ? { ...r, meta: parse(r.meta_json, {}) } : null
}

export function assetPath(asset) {
  // stored_name is generated by us; still refuse anything that is not a plain name.
  if (!/^ast_[\w-]+\.\w+$/.test(asset.stored_name)) throw new Error('bad asset name')
  return path.join(getConfig().paths.assets, asset.stored_name)
}

export function readAsset(asset) {
  return fs.readFileSync(assetPath(asset))
}

/** Can this asset be used in this role on Etsy? Returns a reason string or null. */
export function roleProblem(asset, role) {
  const rule = ROLE_RULES[role]
  if (!rule) return 'Unknown role'
  if (!rule.mimes.includes(asset.mime)) return `${asset.mime} can't be used as a listing ${role}`
  if (asset.size > rule.max) return `Larger than ${Math.round(rule.max / 1048576)} MB`
  return null
}
